-- 제5회 방배페스티벌을 홈 대문에 세웁니다 (회장님이 고른 C안).
--
-- 첫 화면이 축제가 됩니다 — 왼쪽에 제목·일시·같은 날 함께 열리는 행사, 오른쪽에 포스터.
-- 원래 대문(배경사진·검색)은 없어지지 않고 이 아래로 밀려납니다.
--
-- **10월 17일이 지나면 이 대문은 스스로 사라집니다.** 홈을 그리는 질의가 지난 행사를
-- 주지 않기 때문입니다. 그래서 축제가 끝난 뒤에 되돌릴 작업이 없습니다 —
-- 끝난 축제가 첫 화면에 남는 사고를 '기억해서' 막지 않고 구조로 막았습니다.
--
-- 안전장치: 아직 아무 행사도 대문이 아닌 상인회에서만 세웁니다.
--   ① 두 번 돌려도 같습니다.
--   ② 회장님이 다른 행사를 대문으로 고르셨다면 그 선택을 덮어쓰지 않습니다.
UPDATE events SET cover = 1
WHERE title = '제5회 2026 방배페스티벌 — 골목이 카페다'
  AND NOT EXISTS (
    SELECT 1 FROM events x
    WHERE x.association_id = events.association_id AND x.cover = 1
  );
